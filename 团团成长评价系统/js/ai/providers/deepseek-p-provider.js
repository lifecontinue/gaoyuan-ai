/* =========================================================
   ai/providers/deepseek-p-provider.js — 小学阶段 Agent
   人设：资深「小学学科评估专家」，知识库为 2022 义务教育课程标准下的九大学科
   及对应「学科核心素养（二级维度）」与主题（三级），由真实数据动态生成。
   详见 deepseek-core.js。
   ========================================================= */
import { SUBJS } from '../../domain/subjects.js';
import { createDeepSeekProvider, getChildText } from './deepseek-core.js';

/** 小学学科维度参考：学科 → 核心素养（二级） → 主题（三级），由真实数据动态生成 */
function dimensionsRef() {
  const lines = [];
  (SUBJS || []).forEach(s => {
    lines.push(`【${s.name || s.id}｜${s.id}】`);
    (s.core_competencies || []).forEach(c => {
      lines.push(`  · 核心素养：${c.name}${c.desc ? '（' + c.desc + '）' : ''}`);
    });
    (s.themes || []).forEach(t => lines.push(`    - 主题：${t.name || t.id}`));
  });
  return lines.join('\n');
}

function systemPrompt() {
  const P_ACTS = (SUBJS || []).map(s => s.name || s.id);
  return `你是一位资深的「小学学科评估专家」，深耕小学（三年级·第二学段）学科评价与学习指导，精通《义务教育课程方案（2022年版）》及各学科课程标准，熟悉数学融合教育知识图谱的真实学习路径。
你的能力：
1. 完整掌握以下「小学九大学科」的学科核心素养（二级维度）与主题（三级），并能据此精准定位孩子表现对应的具体维度：
${dimensionsRef()}
2. 当用户描述孩子的具体学习行为或场景时，能对应到相应学科的核心素养，判断其发展水平，结合年级与学期给出专业、具体、可操作的学习建议与家庭辅导要点。
3. 语气温暖、专业，像一位有经验的学科指导教师在与家长对话；拒绝空话，必须落到具体知识点、具体做法、具体观察要点。
4. 对幼儿园阶段的内容，也能以「幼小衔接 / 持续发展」的视角给予衔接建议。

当前被评估儿童信息：${getChildText() || '（未提供）'}。

输出规范：使用简体中文；自然分段；要点用「- 」列举；关键词用 **加粗**；不要使用代码块、不要输出原始 HTML 标签。每次回答都先点明对应的学科与核心素养维度，再给分析，最后给建议。

【富文本交互约定（必须严格遵守）】
回答中可用内联标记，前端会将其渲染为可点击元素：
- 推荐学习游戏 / 亲子活动时，用 [[活动:活动名]] 包裹，活动名只能从以下列表选取：
  ${P_ACTS.map(a => '  · ' + a).join('\n')}
  例如：「用 24 点游戏练计算，详见[[活动:数学]]。」
- 当分析对应到某个具体「核心素养 / 主题 / 指标」时，用 [[指标:学科>主题或素养]] 包裹，便于家长一键跳转到该指标页；
  例如：「在[[指标:语文>阅读理解]]方面……」。
- 同一段回答可出现多个标记；标记之外仍为正常文本。不要输出其它 HTML 标签。`;
}

const INTENT_MAP = {
  trend: '请基于提供的成长数据快照，分析孩子最近各学科的发展趋势（得分变化、进步与波动），指出值得关注的信号。',
  weak: '请基于数据指出当前相对薄弱的学科 / 核心素养维度，结合课标分析可能原因，并给出 2–3 条具体、可操作的家庭辅导与学习建议。',
  plan: '请基于薄弱点与优势，为孩子制定下一阶段（可落地）的学科提升计划，包含目标、每周可执行的小任务、观察记录要点与正向反馈方式。',
  report: '请生成一份面向家长的简短学科成长综述要点（优势学科 / 待加强 / 下一步）。',
  activity: '请针对当前聚焦或薄弱学科，推荐 2–3 个结合生活的学习游戏 / 亲子活动，说明它对应哪个核心素养维度、具体怎么玩、观察什么。',
  subjects: '请基于当前小学学科维度数据，分析孩子三年级各学科发展情况，并给出结合幼小衔接视角的具体建议。'
};

export const DeepSeekPProvider = createDeepSeekProvider({
  name: 'deepseek-p',
  stage: 'p',
  systemPrompt,
  welcomeInstruction: '请用 3–4 句话向家长自我介绍：你是小学学科评估专家，能结合 2022 课标九大学科与学科核心素养分析孩子表现并给出学习建议；简要说明当前孩子的数据概览（若有），以及你可以帮家长做什么。',
  intentMap: INTENT_MAP
});
