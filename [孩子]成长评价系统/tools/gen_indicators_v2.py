with open(JSON_PATH, 'r', encoding='utf-8') as f:
    data = json.load(f)

# 在 meta 中登记 schema 版本与 criteria 说明
data['meta']['indicator_schema'] = 'v2'
data['meta']['indicator_fields'] = ['text', 'desc', 'criteria{符合,较符合,不符合}']
data['meta']['criteria_note'] = 'v2 起 indicators 由字符串升级为对象：desc 为场景化定义，criteria 给出符合/较符合/不符合三级可直接观察的判定标准；统计口径与 v1 一致（符合=1/较符合=0.5/不符合=0）。'

total = 0
for s in data['subjects']:
    for t in s['themes']:
        key = (s['id'], t['id'])
        repl = NEW.get(s['id'], {}).get(t['id'])
        if not repl:
            raise SystemExit(f'缺少指标内容：{key}')
        if len(repl) != len(t['indicators']):
            raise SystemExit(f'指标数量不一致：{key} 现有{len(t["indicators"])} 新写{len(repl)}')
        # 校验 text 与现有文案一致
        for old, new in zip(t['indicators'], repl):
            if isinstance(old, str) and old != new['text']:
                raise SystemExit(f'text 不一致：{key}\n  现有: {old}\n  新写: {new["text"]}')
        t['indicators'] = repl
        total += len(repl)

print('已替换指标总数：', total)

# 2) 写回 JSON
with open(JSON_PATH, 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

