/* =========================================================
   ai/prompt-registry.js — 意图提示词注册表
   管理各 AI 意图（趋势/薄弱/计划/报告/活动/学科）的提示词模板。
   本地规则 Provider 不依赖它；云端 LLM Provider 用它拼装 prompt。
   新增意图：在此 register 一条模板即可。
   ========================================================= */

const PROMPTS = {
  trend:    '基于以下成长数据，分析最近几期综合得分率趋势与各领域变化，指出提升最多与变化最小的领域。',
  weak:     '基于以下成长数据，定位最薄弱领域，并列出长期（两期及以上）未完全达标的指标。',
  plan:     '基于以下成长数据，为孩子制定下阶段可执行的提升计划（目标聚焦、记录、打卡、家园对照、正向反馈）。',
  report:   '基于以下成长数据，撰写一份家长可读的综合评价报告。',
  activity: '基于以下成长数据与当前阶段，推荐具体可操作的亲子活动。',
  subjects: '介绍小学三年级各学科评价维度、可评指标与学习路径，并给出学习建议。'
};

export const PromptRegistry = {
  /** 取某意图的提示词模板 */
  get(intent) { return PROMPTS[intent] || ''; },
  /** 注册 / 覆盖某意图模板 */
  register(intent, tpl) { PROMPTS[intent] = tpl; },
  /** 列出全部意图 id */
  list() { return Object.keys(PROMPTS); }
};
